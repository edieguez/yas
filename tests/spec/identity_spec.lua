local F = require("support.fixtures")

local function fixed_os(t)
    return setmetatable({ time = function() return t end }, { __index = os })
end

describe("user ID", function()
    it("generates and persists a 32-character ID when none is configured", function()
        local h = F.boot({ generate_id = true, no_file = true })
        local saved = h:read_state_file("yas_user_id")
        expect.truthy(saved, "ID file written to ~/.local/state/mpv/yas_user_id")
        expect.matches(saved, "^%w+\n$")
        expect.eq(#saved, 33)
    end)

    it("creates the state directory if it doesn't exist", function()
        local h = F.boot({ generate_id = true, no_file = true })
        expect.truthy(h:read_state_file("yas_user_id"))
    end)

    it("makes the ID file readable by its owner only", function()
        local h = F.boot({ generate_id = true, no_file = true })
        local p = io.popen("ls -l '" .. h:state_file("yas_user_id") .. "'")
        local listing = p:read("*a")
        p:close()
        expect.matches(listing, "^%-rw%-%-%-%-%-%-%-")
    end)

    it("logs a masked form of the ID", function()
        local h = F.boot()
        expect.contains(h:log_text("info"), "AbCd…2345")
    end)

    it("reuses the persisted ID on the next launch", function()
        local h1 = F.boot({ generate_id = true })
        local id = h1:read_state_file("yas_user_id"):gsub("%s", "")
        local h2 = F.boot({ generate_id = true, home = h1.home })
        h2:press("z")
        expect.eq(h2:requests_to("GET", "/api/userStats")[1].params.userID, id)
    end)

    it("prefers a valid user_id from yas.conf and doesn't write a file", function()
        local h = F.boot()
        h:press("z")
        expect.eq(h:requests_to("GET", "/api/userStats")[1].params.userID, F.USER_ID)
        expect.is_nil(h:read_state_file("yas_user_id"))
    end)

    it("enables z and ; for a generated ID", function()
        local h = F.boot({ generate_id = true })
        expect.truthy(h:has_binding("z"))
        expect.truthy(h:has_binding(";"))
    end)

    it("disables submission for a configured ID with invalid characters", function()
        local h = F.boot({ conf = { user_id = "abc-def-ghi-jkl-mno-pqr-stu-vwx-yz" } })
        expect.falsy(h:has_binding(";"))
        expect.contains(h:log_text("warn"), "No valid user_id configured")
    end)

    known_bug("L3", "warns when a configured user_id is too short instead of silently replacing it", function()
        local h = F.boot({ conf = { user_id = "short" } })
        expect.contains(h:log_text("warn"), "user_id")
    end)

    it("keeps the private ID out of curl's command line", function()
        local h = F.boot()
        h:press("z")
        F.mark(h, 10, 20)
        h:press("ENTER")
        for _, req in ipairs(h.requests) do
            expect.not_contains(table.concat(req.args, " "), F.USER_ID)
        end
        local stats = h:requests_to("GET", "/api/userStats")[1]
        expect.eq(stats.params.userID, F.USER_ID, "curl still sends it, read from the secret file")
        expect.eq(h:requests_to("POST", "/api/skipSegments")[1].params.userID, F.USER_ID)
    end)

    it("stores the ID for curl in an owner-only file", function()
        local h = F.boot()
        expect.eq(h:read_state_file("yas_secret"), F.USER_ID, "no trailing newline")
        local p = io.popen("ls -l '" .. h:state_file("yas_secret") .. "'")
        local listing = p:read("*a")
        p:close()
        expect.matches(listing, "^%-rw%-%-%-%-%-%-%-")
    end)

    it("sends a submission's userID from the secret file, not in the JSON body", function()
        local h = F.boot()
        F.mark(h, 10, 20)
        h:press("ENTER")
        local post = h:requests_to("POST", "/api/skipSegments")[1]
        expect.eq(post.files, { h:state_file("yas_secret") })
        expect.is_nil(post.json.userID)
    end)

    it("tightens permissions of an ID file written by an older version", function()
        local h0 = F.boot({ generate_id = true, no_file = true })
        os.execute("chmod 644 '" .. h0:state_file("yas_user_id") .. "'")
        local h = F.boot({ generate_id = true, no_file = true, home = h0.home })
        local p = io.popen("ls -l '" .. h:state_file("yas_user_id") .. "'")
        local listing = p:read("*a")
        p:close()
        expect.matches(listing, "^%-rw%-%-%-%-%-%-%-")
    end)

    it("never writes the private ID to the log", function()
        local h = F.boot()
        h:press("z")
        F.mark(h, 10, 20)
        h:press("ENTER")
        expect.not_contains(h:log_text(), F.USER_ID)
    end)

    it("still generates distinct, valid IDs without /dev/urandom (e.g. Windows)", function()
        local real_io, real_open = io, io.open -- the harness swaps the global io while loading
        local no_urandom = setmetatable({ open = function(path, mode)
            if path == "/dev/urandom" then return nil, "no such file" end
            return real_open(path, mode)
        end }, { __index = real_io })
        local a = F.boot({ generate_id = true, no_file = true, env = { io = no_urandom, os = fixed_os(1700000000) } })
        local b = F.boot({ generate_id = true, no_file = true, env = { io = no_urandom, os = fixed_os(1700000000) } })
        expect.matches(a:read_state_file("yas_user_id"), "^%w+\n$")
        expect.eq(#a:read_state_file("yas_user_id"), 33)
        expect.neq(a:read_state_file("yas_user_id"), b:read_state_file("yas_user_id"))
    end)

    it("gives two installs started in the same second different IDs", function()
        local a = F.boot({ generate_id = true, no_file = true, env = { os = fixed_os(1700000000) } })
        local b = F.boot({ generate_id = true, no_file = true, env = { os = fixed_os(1700000000) } })
        expect.neq(a:read_state_file("yas_user_id"), b:read_state_file("yas_user_id"))
    end)
end)
