local F = require("support.fixtures")

describe("skipping", function()
    it("does nothing outside segments", function()
        local h = F.boot({ segments = { F.SPONSOR } })
        h:set_time(10)
        h:set_time(60)
        expect.count(h.seeks, 0)
    end)

    it("seeks just past the end of a skip segment", function()
        local h = F.boot({ segments = { F.SPONSOR } })
        h:set_time(35)
        expect.eq(h.seeks, { 60.001 })
        expect.contains(h:osd_text(), "Skipped Sponsor (30s)")
    end)

    it("reports the skip to SponsorBlock once per segment", function()
        local h = F.boot({ segments = { F.SPONSOR } })
        h:set_time(35)
        h:set_time(40)
        local reports = h:requests_to("POST", "/api/viewedVideoSponsorTime")
        expect.count(reports, 1)
        expect.eq(reports[1].params.UUID, F.SPONSOR.UUID)
    end)

    it("retries the report if it failed", function()
        local h = F.boot({ segments = { F.SPONSOR }, conf = { user_id = F.USER_ID, skip_once = "no" },
            routes = { ["POST /api/viewedVideoSponsorTime"] = { curl_status = 7 } } })
        h:set_time(35)
        h:set_time(40)
        expect.count(h:requests_to("POST", "/api/viewedVideoSponsorTime"), 2)
    end)

    it("skips immediately without waiting for the report to finish", function()
        local h = F.boot({ segments = { F.SPONSOR } })
        h.manual_async = true
        h:set_time(35)
        expect.eq(h.seeks, { 60.001 })
        h:set_time(36) -- report still in flight: don't send a duplicate
        expect.count(h:requests_to("POST", "/api/viewedVideoSponsorTime"), 1)
    end)

    it("records the skip in the local stats file", function()
        local h = F.boot({ segments = { F.SPONSOR } })
        h:set_time(35)
        local stats = h:read_state_file("yas_stats.conf")
        expect.contains(stats, "skip_count=1")
        expect.contains(stats, "minutes_saved=0.5000")
    end)

    it("keeps local stats across restarts", function()
        local h1 = F.boot({ segments = { F.SPONSOR } })
        h1:set_time(35)
        local h2 = F.boot({ home = h1.home, segments = {} })
        h2:press("z")
        expect.contains(h2:screen(), "You've skipped 1 segments (30s)")
    end)

    it("skips a segment the moment playback starts inside it", function()
        local h = F.boot({ segments = { F.segment("eeeeee-intro", "intro", 0, 12) }, no_file = true })
        h.props["time-pos"] = 0
        h:fire("file-loaded")
        expect.eq(h.seeks, { 12.001 })
    end)

end)

describe("muting", function()
    it("mutes for the segment and restores sound afterwards", function()
        local h = F.boot({ segments = { F.MUTE } })
        h:set_time(105)
        expect.eq(h.props.mute, true)
        expect.contains(h:osd_text(), "Muted Unpaid/Self Promotion (20s)")
        h:set_time(121)
        expect.eq(h.props.mute, false)
        expect.count(h.seeks, 0, "mute segments are never skipped")
    end)

    it("leaves audio muted if the viewer had muted it already", function()
        local h = F.boot({ segments = { F.MUTE }, mute = true })
        h:set_time(105)
        h:set_time(121)
        expect.eq(h.props.mute, true)
    end)

    it("restores sound when the viewer seeks out of the segment backwards", function()
        local h = F.boot({ segments = { F.MUTE } })
        h:set_time(105)
        h:set_time(80)
        expect.eq(h.props.mute, false)
    end)

    it("restores sound when the file ends mid-segment", function()
        local h = F.boot({ segments = { F.MUTE } })
        h:set_time(105)
        h:fire("end-file")
        expect.eq(h.props.mute, false)
    end)

    it("does not re-announce while staying inside the segment", function()
        local h = F.boot({ segments = { F.MUTE } })
        h:set_time(105)
        h:set_time(110)
        h:set_time(115)
        expect.count(h:requests_to("POST", "/api/viewedVideoSponsorTime"), 1)
        expect.contains(h:read_state_file("yas_stats.conf"), "skip_count=1")
    end)
end)
