local F = require("support.fixtures")

local function last_submission(h)
    local posts = h:requests_to("POST", "/api/skipSegments")
    return posts[#posts] and posts[#posts].json
end

describe("submission keys", function()
    it("are bound for YouTube videos and removed when the file ends", function()
        local h = F.boot()
        expect.truthy(h:has_binding(";"))
        expect.truthy(h:has_binding(":"))
        h:fire("end-file")
        expect.falsy(h:has_binding(";"))
        expect.falsy(h:has_binding(":"))
    end)

    it("are not bound for other files", function()
        local h = F.boot({ path = "/videos/holiday.mp4" })
        expect.falsy(h:has_binding(";"))
    end)
end)

describe("marking a segment", function()
    it("marks the start and holds the file open at EOF", function()
        local h = F.boot()
        h:set_time(10)
        h:press(";")
        expect.contains(h:osd_text(), "Segment start marked at 10.0 seconds")
        expect.eq(h.props["keep-open"], "always")
    end)

    it("rejects an end before the start and keeps marking", function()
        local h = F.boot()
        h:set_time(10); h:press(";")
        h:set_time(5); h:press(";")
        expect.contains(h:osd_text(), "End time must be after start time")
        h:set_time(20); h:press(";")
        expect.contains(h:screen(), "Submit segment")
    end)

    it("rejects segments shorter than half a second", function()
        local h = F.boot()
        h:set_time(10); h:press(";")
        h:set_time(10.3); h:press(";")
        expect.contains(h:osd_text(), "Segment too short")
        expect.eq(h:forced_count(), 0)
    end)

    it("cancels with : and restores keep-open", function()
        local h = F.boot()
        h:set_time(10); h:press(";")
        h:press(":")
        expect.contains(h:osd_text(), "Segment marking cancelled")
        expect.eq(h.props["keep-open"], "yes")
        h:set_time(30); h:press(";")
        expect.contains(h:osd_text(), "Segment start marked at 30.0 seconds")
    end)

    it("restores a keep-open value other than the default", function()
        local h = F.boot({ keep_open = "no" })
        h:set_time(10); h:press(";")
        h:press(":")
        expect.eq(h.props["keep-open"], "no")
    end)
end)

describe("category dialog", function()
    it("shows the range and all categories", function()
        local h = F.boot()
        F.mark(h, 10, 20)
        local screen = h:screen()
        expect.contains(screen, "Submit segment: 10.0–20.0s (10.0s)")
        expect.contains(screen, "1. Sponsor")
        expect.contains(screen, "8. Non-Music Section")
        expect.eq(h:forced_count(), 12, "arrows, Enter, Esc and 1-8")
    end)

    it("submits the selected category", function()
        local h = F.boot()
        F.mark(h, 10, 20)
        h:press("DOWN"); h:press("DOWN"); h:press("ENTER")
        local body = last_submission(h)
        expect.eq(body.videoID, F.VIDEO_ID)
        expect.eq(body.userID, F.USER_ID)
        expect.eq(body.service, "YouTube")
        expect.eq(body.videoDuration, 600)
        expect.eq(body.segments, { { segment = { 10, 20 }, category = "interaction", actionType = "skip" } })
        expect.contains(h:osd_text(), "Segment submitted successfully")
    end)

    it("cleans up and refreshes segments after submitting", function()
        local h = F.boot()
        F.mark(h, 10, 20)
        h:press("ENTER")
        expect.eq(h:forced_count(), 0)
        expect.eq(h.props["keep-open"], "yes")
        expect.count(h:requests_to("GET", "/api/skipSegments"), 2)
        expect.not_contains(h:screen(), "Submit segment")
    end)

    it("wraps from the first category to the last", function()
        local h = F.boot()
        F.mark(h, 10, 20)
        h:press("UP"); h:press("ENTER")
        expect.eq(last_submission(h).segments[1].category, "music_offtopic")
    end)

    it("jumps to a category with its number key", function()
        local h = F.boot()
        F.mark(h, 10, 20)
        h:press("4"); h:press("ENTER")
        expect.eq(last_submission(h).segments[1].category, "intro")
    end)

    it("cancels with Esc without submitting", function()
        local h = F.boot()
        F.mark(h, 10, 20)
        h:press("ESC")
        expect.count(h:requests_to("POST", "/api/skipSegments"), 0)
        expect.contains(h:osd_text(), "Segment submission cancelled")
        expect.eq(h:forced_count(), 0)
        expect.eq(h.props["keep-open"], "yes")
    end)

    it("ignores ; while the dialog is open", function()
        local h = F.boot()
        F.mark(h, 10, 20)
        h:press(";")
        expect.contains(h:screen(), "Submit segment: 10.0–20.0s")
    end)

    it("moves to the next playlist entry if it was held open at EOF", function()
        local h = F.boot()
        F.mark(h, 590, 600)
        h.props["eof-reached"] = true
        h.props.pause = true
        h:press("ENTER")
        expect.eq(h.commands[#h.commands], { "playlist-next", "weak" })
        expect.eq(h.props.pause, false)
    end)

    it("removes its key bindings if the file ends while it's open", function()
        local h = F.boot()
        F.mark(h, 10, 20)
        h:fire("end-file")
        expect.eq(h:forced_count(), 0)
        expect.eq(h.props["keep-open"], "yes")
    end)

    it("reports a network failure", function()
        local h = F.boot({ routes = { ["POST /api/skipSegments"] = { curl_status = 7 } } })
        F.mark(h, 10, 20)
        h:press("ENTER")
        expect.contains(h:osd_text(), "Failed to submit segment")
    end)

    it("reports a segment the server rejected, with the server's reason", function()
        local h = F.boot({ routes = { ["POST /api/skipSegments"] = { code = 400, body = "Segment is too short" } } })
        F.mark(h, 10, 20)
        h:press("ENTER")
        expect.not_contains(h:osd_text(), "submitted successfully")
        expect.contains(h:osd_text(), "Failed to submit segment: HTTP 400: Segment is too short")
        expect.count(h:requests_to("GET", "/api/skipSegments"), 1, "no refresh after a rejection")
    end)

    it("shows progress while the submission is in flight", function()
        local h = F.boot()
        F.mark(h, 10, 20)
        h.manual_async = true
        h:press("ENTER")
        expect.contains(h:screen(), "Submitting segment…")
        h:flush_async()
        expect.contains(h:screen(), "Segment submitted successfully")
    end)

    it("doesn't refresh segments for a video that is no longer playing", function()
        local h = F.boot()
        F.mark(h, 10, 20)
        h.manual_async = true
        h:press("ENTER")
        h:fire("end-file")
        h:flush_async()
        expect.count(h:requests_to("GET", "/api/skipSegments"), 1)
    end)

    known_bug("UX", "offers the hook category it skips by default", function()
        local h = F.boot()
        F.mark(h, 10, 20)
        expect.contains(h:screen(), "Hook")
    end)

    known_bug("M6", "is not painted over when z is pressed", function()
        local h = F.boot()
        F.mark(h, 10, 20)
        h:press("z")
        expect.contains(h:screen(), "Submit segment")
    end)
end)
