local F = require("support.fixtures")

local HIGHLIGHT = F.segment("hhhhhh-highlight", "poi_highlight", 200, 200, "poi")
local FULL = F.segment("ffffff-full", "exclusive_access", 0, 0, "full")

describe("manual skip mode", function()
    local conf = { user_id = F.USER_ID, manual_skip_categories = "sponsor" }

    it("prompts instead of skipping a manual category", function()
        local h = F.boot({ conf = conf, segments = { F.SPONSOR } })
        h:set_time(35)
        expect.count(h.seeks, 0)
        expect.contains(h:screen(), "Sponsor (30.0s)")
        expect.contains(h:screen(), "ENTER to skip")
    end)

    it("skips when the skip key is pressed", function()
        local h = F.boot({ conf = conf, segments = { F.SPONSOR } })
        h:set_time(35)
        h:press("ENTER")
        expect.eq(h.seeks, { 60.001 })
        expect.count(h:requests_to("POST", "/api/viewedVideoSponsorTime"), 1)
        expect.contains(h:read_state_file("yas_stats.conf"), "skip_count=1")
    end)

    it("withdraws the prompt and its key when playback leaves the segment", function()
        local h = F.boot({ conf = conf, segments = { F.SPONSOR } })
        h:set_time(35)
        h:set_time(61)
        expect.falsy(h:has_binding("ENTER"))
        expect.not_contains(h:screen(), "to skip")
        expect.count(h:requests_to("POST", "/api/viewedVideoSponsorTime"), 0)
    end)

    it("still auto-skips categories that aren't manual", function()
        local h = F.boot({ conf = conf, segments = { F.segment("iiiiii-intro", "intro", 5, 15) } })
        h:set_time(6)
        expect.eq(h.seeks, { 15.001 })
    end)

    it("removes the prompt when the file ends", function()
        local h = F.boot({ conf = conf, segments = { F.SPONSOR } })
        h:set_time(35)
        h:fire("end-file")
        expect.falsy(h:has_binding("ENTER"))
    end)

    it("uses a custom skip key", function()
        local h = F.boot({ conf = { user_id = F.USER_ID, manual_skip_categories = "sponsor", skip_key = "TAB" },
                           segments = { F.SPONSOR } })
        h:set_time(35)
        expect.contains(h:screen(), "TAB to skip")
        h:press("TAB")
        expect.eq(h.seeks, { 60.001 })
    end)
end)

describe("unskip", function()
    it("offers to undo an automatic skip", function()
        local h = F.boot({ segments = { F.SPONSOR } })
        h:set_time(35)
        expect.contains(h:screen(), "ENTER to undo")
        h:press("ENTER")
        expect.eq(h.seeks, { 60.001, 30 })
    end)

    it("doesn't skip the segment again after an undo", function()
        local h = F.boot({ segments = { F.SPONSOR }, conf = { user_id = F.USER_ID, skip_once = "no" } })
        h:set_time(35)
        h:press("ENTER")
        h:set_time(31)
        expect.eq(h.seeks, { 60.001, 30 })
    end)

    it("expires after the undo window", function()
        local h = F.boot({ segments = { F.SPONSOR } })
        h:set_time(35)
        h:run_timers()
        expect.falsy(h:has_binding("ENTER"))
    end)

    it("can be disabled with unskip_window=0", function()
        local h = F.boot({ segments = { F.SPONSOR }, conf = { user_id = F.USER_ID, unskip_window = "0" } })
        h:set_time(35)
        expect.falsy(h:has_binding("ENTER"))
        expect.not_contains(h:screen(), "to undo")
    end)
end)

describe("skip once", function()
    it("doesn't skip a segment again when the viewer seeks back into it", function()
        local h = F.boot({ segments = { F.SPONSOR } })
        h:set_time(35)
        h:set_time(40)
        expect.eq(h.seeks, { 60.001 })
    end)

    it("counts a segment once in the local tally", function()
        local h = F.boot({ segments = { F.SPONSOR } })
        h:set_time(35)
        h:set_time(40)
        expect.contains(h:read_state_file("yas_stats.conf"), "skip_count=1")
    end)

    it("skips every time with skip_once=no", function()
        local h = F.boot({ segments = { F.SPONSOR }, conf = { user_id = F.USER_ID, skip_once = "no" } })
        h:set_time(35)
        h:set_time(40)
        expect.eq(h.seeks, { 60.001, 60.001 })
    end)

    it("starts over on the next file", function()
        local h = F.boot({ segments = { F.SPONSOR } })
        h:set_time(35)
        h:fire("end-file")
        h:fire("file-loaded")
        h:set_time(35)
        expect.eq(h.seeks, { 60.001, 60.001 })
    end)
end)

describe("voting", function()
    it("downvotes the last skipped segment and stops skipping it", function()
        local h = F.boot({ segments = { F.SPONSOR }, conf = { user_id = F.USER_ID, skip_once = "no" } })
        h:set_time(35)
        h:press("Ctrl+b")
        local vote = h:requests_to("POST", "/api/voteOnSponsorTime")[1]
        expect.eq(vote.params.UUID, F.SPONSOR.UUID)
        expect.eq(vote.params.userID, F.USER_ID)
        expect.eq(vote.params.type, "0")
        expect.contains(h:osd_text(), "Downvoted Sponsor segment")
        h:set_time(35)
        expect.count(h.seeks, 1, "a downvoted segment isn't skipped again")
    end)

    it("upvotes the last skipped segment", function()
        local h = F.boot({ segments = { F.SPONSOR } })
        h:set_time(35)
        h:press("Ctrl+g")
        expect.eq(h:requests_to("POST", "/api/voteOnSponsorTime")[1].params.type, "1")
        expect.contains(h:osd_text(), "Upvoted Sponsor segment")
    end)

    it("prefers the segment under the playhead", function()
        local h = F.boot({ segments = { F.SPONSOR, F.MUTE } })
        h:set_time(35)
        h:set_time(105)
        h:press("Ctrl+g")
        expect.eq(h:requests_to("POST", "/api/voteOnSponsorTime")[1].params.UUID, F.MUTE.UUID)
    end)

    it("says so when there is nothing to vote on", function()
        local h = F.boot({ segments = { F.SPONSOR } })
        h:press("Ctrl+g")
        expect.count(h:requests_to("POST", "/api/voteOnSponsorTime"), 0)
        expect.contains(h:osd_text(), "No segment to vote on")
    end)

    it("doesn't send the same vote twice", function()
        local h = F.boot({ segments = { F.SPONSOR } })
        h:set_time(35)
        h:press("Ctrl+g")
        h:press("Ctrl+g")
        expect.count(h:requests_to("POST", "/api/voteOnSponsorTime"), 1)
        expect.contains(h:osd_text(), "Already upvoted")
    end)

    it("shows the server's reason when a vote is rejected, without leaking the user ID", function()
        local h = F.boot({ segments = { F.SPONSOR },
            routes = { ["POST /api/voteOnSponsorTime"] = { code = 403, body = "Vote rejected" } } })
        h:set_time(35)
        h:press("Ctrl+b")
        expect.contains(h:osd_text(), "Vote failed: HTTP 403: Vote rejected")
        expect.not_contains(h:log_text(), F.USER_ID)
        h:press("Ctrl+b")
        expect.count(h:requests_to("POST", "/api/voteOnSponsorTime"), 2, "a failed vote can be retried")
    end)
end)

describe("highlight", function()
    it("requests highlights and adds them as a chapter", function()
        local h = F.boot({ segments = { HIGHLIGHT } })
        local req = h:requests_to("GET", "/api/skipSegments")[1]
        expect.contains(req.params.categories, '"poi_highlight"')
        expect.contains(req.params.actionTypes, '"poi"')
        expect.eq(h.props["chapter-list"], { { title = "Highlight", time = 200 } })
    end)

    it("offers to jump to it near the start of the video", function()
        local h = F.boot({ segments = { HIGHLIGHT } })
        expect.contains(h:screen(), "Highlight at 3:20")
        h:press("ENTER")
        expect.eq(h.seeks, { 200 })
    end)

    it("jumps with the highlight key at any time", function()
        local h = F.boot({ segments = { HIGHLIGHT } })
        h:run_timers()
        h:set_time(50)
        h:press("H")
        expect.eq(h.seeks, { 200 })
    end)

    it("is never skipped", function()
        local h = F.boot({ segments = { HIGHLIGHT } })
        h:set_time(200)
        expect.count(h.seeks, 0)
    end)

    it("isn't offered when playback starts past it", function()
        local h = F.boot({ segments = { HIGHLIGHT }, no_file = true })
        h.props["time-pos"] = 300
        h:fire("file-loaded")
        expect.not_contains(h:screen(), "Highlight at")
    end)

    it("can be turned off", function()
        local h = F.boot({ segments = {}, conf = { user_id = F.USER_ID, highlight = "no" } })
        local req = h:requests_to("GET", "/api/skipSegments")[1]
        expect.not_contains(req.params.categories, "poi_highlight")
        expect.falsy(h:has_binding("H"))
    end)
end)

describe("full-video labels", function()
    it("requests full-video labels", function()
        local h = F.boot({ segments = {} })
        local req = h:requests_to("GET", "/api/skipSegments")[1]
        expect.contains(req.params.categories, '"exclusive_access"')
        expect.contains(req.params.actionTypes, '"full"')
    end)

    it("announces the label without skipping or adding chapters", function()
        local h = F.boot({ segments = { FULL } })
        h:set_time(0)
        expect.contains(h:osd_text(), "Entire video: Exclusive Access")
        expect.count(h.seeks, 0)
        expect.eq(#h.props["chapter-list"], 0)
    end)

    it("can be turned off", function()
        local h = F.boot({ segments = {}, conf = { user_id = F.USER_ID, full_video_labels = "no" } })
        local req = h:requests_to("GET", "/api/skipSegments")[1]
        expect.not_contains(req.params.categories, "exclusive_access")
        expect.not_contains(req.params.actionTypes, "full")
    end)
end)

describe("prompts and other UI", function()
    local manual = { user_id = F.USER_ID, manual_skip_categories = "sponsor" }

    it("binds the skip key as a normal key, so console and input.conf keep priority", function()
        local h = F.boot({ segments = { F.SPONSOR } })
        h:set_time(35)
        expect.truthy(h.bindings.yas_action, "bound while the undo is offered")
        expect.falsy(h.bindings.yas_action.forced)
    end)

    it("keeps a manual prompt on screen when another toast appears", function()
        local h = F.boot({ conf = manual, segments = { F.SPONSOR } })
        h:set_time(35)
        h:press("Ctrl+g")
        expect.contains(h:screen(), "Upvoted Sponsor segment")
        expect.contains(h:screen(), "ENTER to skip")
        h:run_timers()
        expect.contains(h:screen(), "ENTER to skip", "lasts as long as the key works")
    end)

    it("doesn't promise an undo it can't offer", function()
        local h = F.boot({ segments = { F.SPONSOR } })
        h:set_time(10); h:press(";")
        h:set_time(20); h:press(";")     -- dialog open
        h:set_time(35)                    -- skip happens behind the dialog
        expect.contains(h:osd_text(), "Skipped Sponsor (30.0s)")
        expect.not_contains(h:screen(), "to undo")
    end)

    it("withdraws a manual prompt as soon as its segment is downvoted", function()
        local h = F.boot({ conf = manual, segments = { F.SPONSOR } })
        h:set_time(35)
        h:press("Ctrl+b")
        expect.falsy(h:has_binding("ENTER"))
        expect.not_contains(h:screen(), "to skip")
    end)

    it("unmutes right away when the muted segment is downvoted", function()
        local h = F.boot({ segments = { F.MUTE } })
        h:set_time(105)
        h:press("Ctrl+b")
        expect.eq(h.props.mute, false)
        h:set_time(110)
        expect.eq(h.props.mute, false)
    end)

    it("doesn't show a vote result on the next video", function()
        local h = F.boot({ segments = { F.SPONSOR } })
        h:set_time(35)
        h.manual_async = true
        h:press("Ctrl+g")
        h:fire("end-file")
        h:flush_async()
        expect.not_contains(h:osd_text(), "Upvoted")
    end)

    it("shows the full-video label alongside the highlight prompt", function()
        local h = F.boot({ segments = { FULL, HIGHLIGHT } })
        expect.contains(h:screen(), "Entire video: Exclusive Access")
        expect.contains(h:screen(), "Highlight at 3:20")
    end)

    it("fetches manual-skip categories even if they aren't in categories", function()
        local h = F.boot({ conf = { user_id = F.USER_ID, categories = "sponsor",
                                    manual_skip_categories = "music_offtopic" } })
        expect.contains(h:requests_to("GET", "/api/skipSegments")[1].params.categories, '"music_offtopic"')
    end)

    it("turns prompts off with an empty skip_key", function()
        local h = F.boot({ conf = { user_id = F.USER_ID, skip_key = "" }, segments = { F.SPONSOR, HIGHLIGHT } })
        expect.falsy(h.bindings.yas_action)
        h:set_time(35)
        expect.falsy(h.bindings.yas_action)
        expect.eq(h.seeks, { 60.001 }, "still skips")
    end)

    it("keeps prompts away from ENTER while a chapter name is being typed", function()
        local h = F.boot({ segments = { F.SPONSOR } })
        F.mark(h, 10, 20)
        h:press("UP"); h:press("UP"); h:press("ENTER")   -- Chapter: name prompt open
        h:set_time(35)                                    -- auto-skip meanwhile
        expect.falsy(h.bindings.yas_action)
        h.input_prompt.submit("Setup")
        h:flush_async()
        expect.eq(h:requests_to("POST", "/api/skipSegments")[1].json.segments[1].description, "Setup")
    end)

    it("doesn't submit a chapter to the next video", function()
        local h = F.boot()
        F.mark(h, 10, 20)
        h:press("UP"); h:press("UP"); h:press("ENTER")
        local prompt = h.input_prompt
        h:fire("end-file")
        expect.is_nil(h.input_prompt, "the prompt is closed with the file")
        prompt.submit("Setup")
        expect.count(h:requests_to("POST", "/api/skipSegments"), 0)
    end)
end)
